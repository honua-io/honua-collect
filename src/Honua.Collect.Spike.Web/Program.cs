using Honua.Collect.Spike.Shared;
using Honua.Collect.Spike.Web;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddRazorComponents().AddInteractiveServerComponents();
var directory = Environment.GetEnvironmentVariable("COLLECT_SPIKE_DATA") ?? Path.Combine(Path.GetTempPath(), "honua-collect-shell-spike");
Directory.CreateDirectory(directory);
builder.Services.AddScoped(_ => new SpikeStore(directory));
var app = builder.Build();
app.UseAntiforgery();
app.MapStaticAssets();
app.MapRazorComponents<App>().AddInteractiveServerRenderMode().AddAdditionalAssemblies(typeof(Shell).Assembly);
app.Run();
